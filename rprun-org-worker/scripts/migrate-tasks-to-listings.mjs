// scripts/migrate-tasks-to-listings.mjs
// 阶段 4 数据迁移：把 tasks 表里 status='PUBLISHED' 的任务导出为 listings 行。
// 输入：通过环境变量 DATA_FILE 指定的 JSON 文件路径。
//   JSON 来自：`wrangler d1 execute ... --json`
// 输出：标准输出是 INSERT 语句列表，可写入 SQL 文件再用 wrangler d1 execute --file 灌入。
//
// 规则：
//   - 单 item 任务 → 1 条 listing
//   - 多 item 任务 → N 条 listing（按 items 顺序，listing_id = migrated-<taskId>-<idx>）
//   - status 固定为 'OPEN'（迁移后相当于发布时的初始状态）
//   - 老 task 行不删除、不修改（迁移期兼容）

import { readFileSync } from 'node:fs';

const dataFile = process.argv[2];
if (!dataFile) {
  console.error('Usage: node migrate-tasks-to-listings.mjs <data.json>');
  process.exit(1);
}

const raw = readFileSync(dataFile, 'utf8');
// wrangler --json 输出在 PowerShell 里可能被附加 banner 行；trim 找到 '['
const startIdx = raw.indexOf('[');
if (startIdx < 0) {
  console.error('No [ found in input');
  process.exit(1);
}
let jsonText = raw.slice(startIdx);
// 找到匹配的 ']' 结尾（最外层）
let depth = 0;
let endIdx = -1;
for (let i = 0; i < jsonText.length; i++) {
  if (jsonText[i] === '[') depth++;
  else if (jsonText[i] === ']') {
    depth--;
    if (depth === 0) { endIdx = i; break; }
  }
}
if (endIdx < 0) {
  console.error('No matching ] in input');
  process.exit(1);
}
const json = jsonText.slice(0, endIdx + 1);

const arr = JSON.parse(json);
// arr[0].results 是行数组
const tasks = arr[0]?.results ?? arr;

function sqlEscape(s) {
  if (s === null || s === undefined) return 'NULL';
  return `'${String(s).replace(/'/g, "''")}'`;
}

function nowIso() {
  return new Date().toISOString().replace('T', ' ').replace(/\.\d{3}Z$/, '');
}

const out = [];
for (const task of tasks) {
  let cj;
  try {
    cj = JSON.parse(task.contract_json);
  } catch (e) {
    console.error(`Skip task ${task.id}: contract_json not JSON: ${e.message}`);
    continue;
  }
  const type = task.type;
  const currency = cj.currency;
  const location = cj.location ?? null;
  const origin = cj.origin ?? null;
  const destination = cj.destination ?? null;
  const createdAt = task.created_at ?? nowIso();
  const updatedAt = task.updated_at ?? createdAt;

  for (let i = 0; i < cj.items.length; i++) {
    const item = cj.items[i];
    const listingId = cj.items.length === 1
      ? `migrated-${task.id}`
      : `migrated-${task.id}-${i}`;
    const amount = item.amount;
    const price = item.price ?? 0;
    const commodity = item.commodity;
    out.push(
      `INSERT OR IGNORE INTO listings (id, type, commodity, amount, remaining_amount, price, currency, location, origin, destination, publisher_id, publisher_username, publisher_company_code, status, created_at, updated_at) VALUES (${sqlEscape(listingId)}, ${sqlEscape(type)}, ${sqlEscape(commodity)}, ${amount}, ${amount}, ${price}, ${sqlEscape(currency)}, ${sqlEscape(location)}, ${sqlEscape(origin)}, ${sqlEscape(destination)}, ${sqlEscape(task.publisher_id)}, ${sqlEscape(task.publisher_username)}, ${sqlEscape(task.publisher_company_code)}, 'OPEN', ${sqlEscape(createdAt)}, ${sqlEscape(updatedAt)});`
    );
  }
}

process.stdout.write('-- Auto-generated by migrate-tasks-to-listings.mjs\n');
process.stdout.write('-- Transfers PUBLISHED tasks into listings table\n');
process.stdout.write(out.join('\n') + '\n');
process.stdout.write(`-- ${out.length} listings to insert\n`);